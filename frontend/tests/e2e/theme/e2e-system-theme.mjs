import assert from "node:assert/strict";
import { chromium } from "playwright";

const web = process.env.E2E_BASE_URL ?? "http://localhost:5173";
const key = "interview-online:ui-theme";
const browser = await chromium.launch();
try {
  const context = await browser.newContext({ colorScheme: "dark" });
  await context.routeWebSocket("**/ws", (socket) => socket.close());
  await context.addInitScript(() => {
    requestAnimationFrame(() => { window.__themeAtFirstFrame = document.documentElement.dataset.theme; });
  });
  const page = await context.newPage();
  await page.goto(web, { waitUntil: "networkidle" });
  assert.equal(await page.locator("html").getAttribute("data-theme"), "dark", "a first visit follows the operating system");
  assert.equal(await page.evaluate(() => window.__themeAtFirstFrame), "dark", "bootstrap applies the operating system before the first paint");
  assert.equal(await page.evaluate((key) => localStorage.getItem(key), key), null, "automatic appearance is not saved as an explicit choice");
  await page.emulateMedia({ colorScheme: "light" });
  await page.waitForFunction(() => document.documentElement.dataset.theme === "light");
  await page.emulateMedia({ colorScheme: "dark" });
  await page.waitForFunction(() => document.documentElement.dataset.theme === "dark");
  await page.getByRole("button", { name: "Тёмная тема", exact: true }).click();
  await page.waitForFunction(() => document.documentElement.dataset.theme === "light");
  assert.equal(await page.evaluate((key) => localStorage.getItem(key), key), "light");
  await page.emulateMedia({ colorScheme: "light" });
  await page.emulateMedia({ colorScheme: "dark" });
  await page.waitForTimeout(100);
  assert.equal(await page.locator("html").getAttribute("data-theme"), "light", "manual light choice has priority over the operating system");
  await page.reload({ waitUntil: "networkidle" });
  assert.equal(await page.evaluate(() => window.__themeAtFirstFrame), "light", "manual choice survives a reload without a dark flash");
  const second = await context.newPage();
  await second.goto(web, { waitUntil: "networkidle" });
  await second.getByRole("button", { name: "Тёмная тема", exact: true }).click();
  await page.waitForFunction(() => document.documentElement.dataset.theme === "dark");
  await second.evaluate((key) => localStorage.removeItem(key), key);
  await page.emulateMedia({ colorScheme: "light" });
  await page.waitForFunction(() => document.documentElement.dataset.theme === "light");
  assert.equal(await page.evaluate((key) => localStorage.getItem(key), key), null);
  await page.emulateMedia({ colorScheme: "dark" });
  await page.waitForFunction(() => document.documentElement.dataset.theme === "dark");
  await second.reload({ waitUntil: "networkidle" });
  assert.equal(await second.locator("html").getAttribute("data-theme"), "dark", "removing an explicit preference returns other tabs and reloads to system appearance");
  await second.evaluate((key) => localStorage.setItem(key, "invalid"), key);
  await page.emulateMedia({ colorScheme: "light" });
  await page.waitForFunction(() => document.documentElement.dataset.theme === "light");
  await page.emulateMedia({ colorScheme: "dark" });
  await page.waitForFunction(() => document.documentElement.dataset.theme === "dark");
  await second.getByRole("button", { name: "Тёмная тема", exact: true }).click();
  await page.waitForFunction(() => document.documentElement.dataset.theme === "light");
  await second.evaluate(() => localStorage.clear());
  await page.waitForFunction(() => document.documentElement.dataset.theme === "dark");
  assert.equal(await page.evaluate((key) => localStorage.getItem(key), key), null, "clearing preferences in another tab also returns to the operating system");
  await context.close();
  const blocked = await browser.newContext({ colorScheme: "dark" });
  await blocked.addInitScript(() => {
    const getItem = Storage.prototype.getItem;
    const setItem = Storage.prototype.setItem;
    Storage.prototype.getItem = function(key) { if (key === "interview-online:ui-theme") throw new DOMException("Blocked", "SecurityError"); return getItem.call(this, key); };
    Storage.prototype.setItem = function(key, value) { if (key === "interview-online:ui-theme") throw new DOMException("Blocked", "SecurityError"); return setItem.call(this, key, value); };
  });
  const blockedPage = await blocked.newPage();
  await blockedPage.goto(web, { waitUntil: "networkidle" });
  assert.equal(await blockedPage.locator("html").getAttribute("data-theme"), "dark", "blocked storage still follows the operating system");
  await blockedPage.getByRole("button", { name: "Тёмная тема", exact: true }).click();
  await blockedPage.emulateMedia({ colorScheme: "light" });
  await blockedPage.emulateMedia({ colorScheme: "dark" });
  assert.equal(await blockedPage.locator("html").getAttribute("data-theme"), "light", "manual choice still works for the current tab with blocked storage");
  await blocked.close();
} finally { await browser.close(); }
console.log("System theme, first paint, manual priority, cross-tab removal and blocked storage passed");
