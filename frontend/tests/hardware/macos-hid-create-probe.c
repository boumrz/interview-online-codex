static int probe(const unsigned char *descriptor, size_t length, CFStringRef product) {
  CFMutableDictionaryRef props=CFDictionaryCreateMutable(NULL,0,&kCFTypeDictionaryKeyCallBacks,&kCFTypeDictionaryValueCallBacks);
  CFDataRef data=CFDataCreate(NULL,descriptor,(CFIndex)length);
  CFDictionarySetValue(props,CFSTR(kIOHIDReportDescriptorKey),data);
  CFDictionarySetValue(props,CFSTR(kIOHIDProductKey),product);
  CFDictionarySetValue(props,CFSTR(kIOHIDManufacturerKey),CFSTR("InterHub isolated validation"));
  IOHIDUserDeviceRef device=IOHIDUserDeviceCreateWithProperties(NULL,props,0);
  int created=device!=NULL;
  if(device) CFRelease(device);
  CFRelease(data); CFRelease(props);
  return created;
}
